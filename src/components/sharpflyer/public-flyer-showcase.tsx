"use client";

import * as React from "react";
import { Check, Eye } from "lucide-react";

import { Button } from "@/components/ui/button";
import { FORMAT_SIZES, type FlyerFormat } from "@/schemas/format";

export function PublicFlyerShowcase({ templateId, templateTitle, format }: { templateId: string; templateTitle: string; format: FlyerFormat }) {
  const [view, setView] = React.useState<"before" | "after">("after");
  const dimensions = FORMAT_SIZES[format];
  const imagePath = `/api/templates/${templateId}/preview?format=${format}&sample=${view}`;

  return (
    <div className="flex flex-col gap-4 rounded-[28px] bg-surface p-4 shadow-2 sm:p-5">
      <div className="flex items-center justify-between gap-3"><div><p className="text-caption text-muted-foreground">Live template example</p><h2 className="mt-1 text-h4 text-foreground">{templateTitle}</h2></div><Eye className="size-5 text-muted-foreground" aria-hidden="true" /></div>
      <div className="flex gap-2" role="group" aria-label="Before and after example">
        {(["before", "after"] as const).map((item) => <Button key={item} type="button" variant={view === item ? "default" : "secondary"} size="sm" onClick={() => setView(item)}>{view === item && <Check />}{item === "before" ? "Template" : "Filled in"}</Button>)}
      </div>
      <figure className="overflow-hidden rounded-[20px] bg-background" aria-live="polite">
        {/* The image is generated by the same renderer used for app previews. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={imagePath} alt={`${templateTitle}, ${view === "before" ? "template" : "filled-in"} example`} width={dimensions.width} height={dimensions.height} className="h-auto max-h-[min(68dvh,680px)] w-full object-contain" />
      </figure>
      <p className="text-caption text-muted-foreground">{view === "before" ? "Start with a real template." : "Your structured details stay readable and accurate."}</p>
    </div>
  );
}
