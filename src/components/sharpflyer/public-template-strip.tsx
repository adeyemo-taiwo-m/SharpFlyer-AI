import Link from "next/link";

import type { TemplateSummary } from "@/server/templates";
import { FORMAT_SIZES, type FlyerFormat } from "@/schemas/format";

export function PublicTemplateStrip({ templates }: { templates: TemplateSummary[] }) {
  return (
    <div className="flex flex-wrap gap-5">
      {templates.slice(0, 4).map((template) => {
        const format: FlyerFormat = template.formats.includes("ig_post") ? "ig_post" : (template.formats[0] ?? "ig_post");
        const dimensions = FORMAT_SIZES[format];
        return <Link key={`${template.id}@${template.version}`} href="/app/templates" className="group flex min-w-0 basis-[calc(50%-0.625rem)] flex-col gap-3 outline-none focus-visible:ring-2 focus-visible:ring-ring md:basis-[calc(25%-0.95rem)]">
          <div className="overflow-hidden rounded-[20px] bg-surface transition-shadow group-hover:shadow-2" style={{ aspectRatio: `${dimensions.width} / ${dimensions.height}` }}>
            {/* This preview is generated by the real renderer-backed API. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={`/api/templates/${template.id}/preview?format=${format}`} alt={`${template.title} flyer template`} width={dimensions.width} height={dimensions.height} loading="lazy" className="h-full w-full object-cover" />
          </div>
          <span className="text-callout text-foreground">{template.title}</span>
        </Link>;
      })}
    </div>
  );
}
